# Builds bot/functions/ziso-bot/knowledge.ts from the site content (src/content.py + guide pages),
# so the bot answers from the same approved copy the site shows. Run after editing content:
#   python3 bot/build_knowledge.py && (redeploy the ziso-bot edge function)
import json, os, re, sys, urllib.parse
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "src"))
from content import *  # noqa

def strip(s):
  return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", s)).strip()

def para(x):
  # content.py bodies mix strings (paragraphs) and lists (bullets)
  if isinstance(x, str): return strip(x)
  return " ".join("• " + strip(i) for i in x)

lines = ["## העסק",
  'זיסו קרמיקה בע"מ (ZISO CERAMICS LTD), עסק משפחתי מאז 1985, מנוהל על ידי משה ואילת. אולם תצוגה: עוצמה 5, טירת כרמל (דקות מחיפה, נשר והקריות).',
  "טלפון וואטסאפ: %s. אימייל: %s. אתר: %s" % (PHONE, EMAIL, SITE),
  "שעות פתיחה: ראשון–חמישי 08:00–18:00, שישי 08:00–13:30, שבת סגור (בשבת אף אחד לא עונה לטלפון; אפשר להשאיר הודעה בוואטסאפ ונחזור ביום העבודה הבא).",
  "אזורי שירות: " + ", ".join(AREAS) + ".",
  "פגישת ייעוץ ועיצוב באולם: בחינם ובלי התחייבות, עם אילת ושיר, מעצבות פנים מוסמכות. מתאמים מראש בוואטסאפ. הצעת מחיר מסודרת תוך 24 שעות מהביקור.",
  "קישור לתיאום בוואטסאפ: https://wa.me/%s . ניווט בוויז: https://waze.com/ul?q=%s&navigate=yes" % (WA, urllib.parse.quote("עוצמה 5 טירת כרמל")),
  "דף יצירת קשר: %scontact.html . מחשבון כמויות: %scalculator.html . טופס תיק לקוח: %stik-lakoach.html" % (SITE, SITE, SITE),
  "מוצרים: " + ", ".join(c["name"] for c in CATS) + ".",
  "", "## שאלות נפוצות"]
for q, a in HOME_FAQ: lines.append("ש: %s\nת: %s" % (strip(q), strip(a)))
for c in CATS:
  lines += ["", "## %s (%s%s.html)" % (c["name"], SITE, c["slug"]), strip(c["card"]), strip(c["lede"])]
  if c.get("sizes"): lines.append("פורמטים: " + c["sizes"])
  for title, body in c["body"]:
    if body == "TABLE":
      lines.append(title + ": " + "; ".join(" / ".join(r) for r in c["table"][1:]))
    else:
      lines.append(strip(title) + ": " + " ".join(para(p) for p in body))
  for q, a in c.get("faq", []): lines.append("ש: %s\nת: %s" % (strip(q), strip(a)))

lines += ["", "## מדריכים באתר (אפשר לקשר אליהם)"]
gd = os.path.join(HERE, "..", "src", "pages", "guides")
for fn in sorted(os.listdir(gd)):
  if not fn.endswith(".md"): continue
  meta = {}
  for ln in open(os.path.join(gd, fn), encoding="utf-8").read().split("---")[1].splitlines():
    if ":" in ln:
      k, v = ln.split(":", 1); meta[k.strip()] = v.strip()
  lines.append("- %s: %s (%sguide-%s.html)" % (meta.get("h1", fn), meta.get("answer", ""), SITE, fn[:-3]))

text = "\n".join(lines)
out = os.path.join(HERE, "functions", "ziso-bot", "knowledge.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write("// Generated by bot/build_knowledge.py from src/content.py; do not edit by hand.\nexport const KNOWLEDGE = %s;\n" % json.dumps(text, ensure_ascii=False))
print(out, len(text), "chars")
