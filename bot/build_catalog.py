# Builds bot/functions/ziso-bot/catalog.ts (item family + description only) from a Priority items export,
# so the bot can say whether something similar exists. No prices, stock, costs, suppliers or codes leave Priority.
#   python3 bot/build_catalog.py "/mnt/project-files/cfo/eran-package/05-ייצוא-פריטים-פריוריטי-13.10.2026.xlsx"
# The export screen is capped at 2,000 rows (priority-partial-export-guard), so the list can be incomplete.
import json, os, sys, re, zipfile, xml.etree.ElementTree as ET
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else "/mnt/project-files/cfo/eran-package/05-ייצוא-פריטים-פריוריטי-13.10.2026.xlsx"
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}

def rows(path):
  # Minimal xlsx reader (openpyxl rejects Priority's stylesheet). Shared strings + inline strings only.
  z = zipfile.ZipFile(path)
  ss = [("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"]))) for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS)] if "xl/sharedStrings.xml" in z.namelist() else []
  sheet = ET.fromstring(z.read("xl/worksheets/sheet1.xml"))
  for r in sheet.iter("{%s}row" % NS["m"]):
    out = {}
    for c in r.findall("m:c", NS):
      col = re.match(r"[A-Z]+", c.get("r")).group(0)
      v = c.find("m:v", NS); t = c.get("t")
      if t == "s" and v is not None: out[col] = ss[int(v.text)]
      elif t == "inlineStr": out[col] = "".join(x.text or "" for x in c.iter("{%s}t" % NS["m"]))
      elif v is not None: out[col] = v.text
    yield out

it = rows(SRC)
hdr = next(it)
col = {v.replace("‎", "").replace("*", "").strip(): k for k, v in hdr.items()}
c_code, c_desc, c_fam, c_status = col['מק"ט'], col["תאור"], col["תאור משפחה"], col["סטטוס"]
# Custom orders are often described with the customer's name ("ארון 100 לעידן כהן", "עבור סמי אמר"); none of those may leak.
PRIVATE = re.compile(r"(לעידן|כהן|לחיה|בן הרוש|אמיר מדר|לנילי|מעיין|קופרייב|קרויטרו|מור ושגיא|להירש|ליואב|ענבל מרום|לאילן|דור רפאל|סמי אמר|רז נבון|ניר עציון|למלון|עבור |אצלי|לתצוגה|ליעד|לגל )")
items, fams = [], {}
for r in it:
  code, desc, fam = (r.get(c_code) or "").strip(), re.sub(r"\s+", " ", (r.get(c_desc) or "")).strip(), (r.get(c_fam) or "").strip()
  if r.get(c_status) != "פעיל" or code == "000" or not desc or not fam or fam == "משפחת מוצר כללית": continue
  if PRIVATE.search(desc): continue  # one-off orders named after a customer stay out of the bot
  items.append([fam, desc]); fams[fam] = fams.get(fam, 0) + 1
by_fam = {}  # family -> sorted unique descriptions (duplicates collapse, family written once)
for fam, desc in items: by_fam.setdefault(fam, set()).add(desc)
by_fam = {f: sorted(d) for f, d in sorted(by_fam.items())}
outdir = os.path.join(HERE, "functions", "ziso-bot")
# Split into ~18K-char parts so each file stays small enough for the deploy tooling; catalog.ts merges them.
parts, cur, size = [], {}, 0
for fam, descs in by_fam.items():
  cur[fam] = descs; size += sum(len(d) + 4 for d in descs)
  if size > 18000: parts.append(cur); cur, size = {}, 0
if cur: parts.append(cur)
for i, part in enumerate(parts, 1):
  open(os.path.join(outdir, "catalog-%d.ts" % i), "w", encoding="utf-8").write(
    "// Generated by bot/build_catalog.py (part %d of %d). Family -> item descriptions.\nexport const PART: Record<string, string[]> = %s;\n"
    % (i, len(parts), json.dumps(part, ensure_ascii=False, separators=(",", ":"))))
out = os.path.join(outdir, "catalog.ts")
open(out, "w", encoding="utf-8").write(
  "// Generated by bot/build_catalog.py from a Priority items export (%s). Family + description only, no prices or stock.\n%s"
  "export const FAMILIES: Record<string, number> = %s;\n"
  "export const CATALOG: Record<string, string[]> = Object.assign({}, %s);\n"
  % (os.path.basename(SRC), "".join('import { PART as P%d } from "./catalog-%d.ts";\n' % (i, i) for i in range(1, len(parts) + 1)),
     json.dumps(fams, ensure_ascii=False), ", ".join("P%d" % i for i in range(1, len(parts) + 1))))
print(out, sum(len(v) for v in by_fam.values()), "items,", len(by_fam), "families,", len(parts), "parts")
